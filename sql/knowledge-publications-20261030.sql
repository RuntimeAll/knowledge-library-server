CREATE TABLE kb_publication (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  row_version BIGINT NOT NULL DEFAULT 0 COMMENT '当前行并发版本',
  create_by VARCHAR(64) NOT NULL DEFAULT '' COMMENT '创建者',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_by VARCHAR(64) NOT NULL DEFAULT '' COMMENT '更新者',
  update_time DATETIME NULL DEFAULT NULL COMMENT '更新时间',
  title VARCHAR(300) NOT NULL COMMENT '后台资料名称',
  post_title VARCHAR(300) NULL DEFAULT NULL COMMENT '发布标题',
  post_body MEDIUMTEXT NULL COMMENT '完整发布正文',
  listing_description MEDIUMTEXT NULL COMMENT '商品上架描述',
  status VARCHAR(16) NOT NULL DEFAULT 'PREPARING' COMMENT 'PREPARING准备中/ON_SALE已发售/DELETED已删除',
  content_version BIGINT NOT NULL DEFAULT 1 COMMENT '内容或关联修改时递增；不因链接生成结果变化递增',
  origin_system VARCHAR(64) COLLATE utf8mb4_bin NULL DEFAULT NULL COMMENT '旧发布台或来源系统身份，与旧记录键一起保存',
  origin_record_key VARCHAR(160) COLLATE utf8mb4_bin NULL DEFAULT NULL COMMENT '旧记录稳定键；新记录可空',
  legacy_sale_status VARCHAR(20) NULL DEFAULT NULL COMMENT 'SOLD/NOT_SOLD/UNKNOWN；只存历史事实',
  legacy_sold_at DATETIME NULL DEFAULT NULL COMMENT '旧发售时间，未知为空',
  share_code CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '已发售后生成的随机公开地址标识；不是管理令牌',
  share_state VARCHAR(16) NOT NULL DEFAULT 'NOT_CREATED' COMMENT 'NOT_CREATED/BUILDING/READY/FAILED/DISABLED；技术状态',
  share_asset_id BIGINT NULL DEFAULT NULL COMMENT '当前有效分享HTML或入口资产，引用kb_asset',
  shared_content_version BIGINT NULL DEFAULT NULL COMMENT '当前可访问分享内容版本，成功生成后写入',
  last_sale_operation_id BIGINT NULL DEFAULT NULL COMMENT '当前或最近成功发售操作，撤回后留作历史',
  sold_at DATETIME NULL DEFAULT NULL COMMENT '最近一次成功发售时间',
  deleted_at DATETIME NULL DEFAULT NULL COMMENT '逻辑删除时间；恢复清空',
  remark VARCHAR(500) NULL DEFAULT NULL COMMENT '业务备注',
  PRIMARY KEY (id),
  UNIQUE KEY uk_pub_origin (origin_system, origin_record_key),
  UNIQUE KEY uk_pub_share (share_code),
  KEY idx_pub_state_time (status, create_time, id),
  KEY idx_pub_title (title),
  CONSTRAINT fk_pub_share_asset FOREIGN KEY (share_asset_id) REFERENCES kb_asset (asset_id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='发布资料主表';

